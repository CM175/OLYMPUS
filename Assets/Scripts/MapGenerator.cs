        /// <summary>
        /// Extrudes a CONVEX, counter-clockwise (x right, y up) polygon along Z (centred on 0).
        /// Flat-shaded; every triangle owns its vertices. preRotation is baked into the vertices.
        /// </summary>
        static Mesh BuildPrismMesh(IList<Vector2> poly, float thickness, Quaternion preRotation, string meshName)
        {
            var verts = new List<Vector3>();
            var tris = new List<int>();
            var uvs = new List<Vector2>();
            float h = thickness * 0.5f;
            int n = poly.Count;

            for (int i = 1; i < n - 1; i++)
            {
                AddTri(verts, tris, uvs, preRotation, V3(poly[0], h), V3(poly[i], h), V3(poly[i + 1], h));      // +Z cap
                AddTri(verts, tris, uvs, preRotation, V3(poly[0], -h), V3(poly[i + 1], -h), V3(poly[i], -h));   // -Z cap
            }
            for (int i = 0; i < n; i++)
            {
                Vector2 p = poly[i], q = poly[(i + 1) % n];
                Vector3 a = V3(p, h), b = V3(q, h), c = V3(q, -h), d = V3(p, -h);
                AddTri(verts, tris, uvs, preRotation, a, c, b);
                AddTri(verts, tris, uvs, preRotation, a, d, c);
            }

            var mesh = new Mesh { name = meshName };
            mesh.SetVertices(verts);
            mesh.SetUVs(0, uvs);
            mesh.SetTriangles(tris, 0);
            mesh.RecalculateNormals();
            mesh.RecalculateBounds();
            return mesh;
        }

        static Vector3 V3(Vector2 p, float z) { return new Vector3(p.x, p.y, z); }

        static void AddTri(List<Vector3> v, List<int> t, List<Vector2> uv, Quaternion rot, Vector3 a, Vector3 b, Vector3 c)
        {
            a = rot * a; b = rot * b; c = rot * c;
            Vector3 n = Vector3.Cross(b - a, c - a);
            Vector3 an = new Vector3(Mathf.Abs(n.x), Mathf.Abs(n.y), Mathf.Abs(n.z));
            int i = v.Count;
            v.Add(a); v.Add(b); v.Add(c);
            t.Add(i); t.Add(i + 1); t.Add(i + 2);
            uv.Add(PlanarUV(a, an)); uv.Add(PlanarUV(b, an)); uv.Add(PlanarUV(c, an));
        }

        static Vector2 PlanarUV(Vector3 p, Vector3 absNormal)
        {
            if (absNormal.x >= absNormal.y && absNormal.x >= absNormal.z) return new Vector2(p.z, p.y);
            if (absNormal.y >= absNormal.z) return new Vector2(p.x, p.z);
            return new Vector2(p.x, p.y);
        }

        // ==================================================================================
        //  GIZMOS: see the blueprint without generating anything
        // ==================================================================================
        void OnDrawGizmosSelected()
        {
            if (!drawBlueprintGizmos) return;
            if (_grid == null || _parsedBlueprint != blueprint) ParseBlueprint();

            Matrix4x4 prev = Gizmos.matrix;
            Gizmos.matrix = transform.localToWorldMatrix;

            for (int half = 0; half < 2; half++)
                for (int r = 0; r < _rows; r++)
                    for (int c = 0; c < _cols; c++)
                    {
                        char ch = _grid[r, c];
                        if (ch == '.' || IsReserved(r, c)) continue;
                        Gizmos.color = GizmoColor(ch, half);
                        Vector3 p = ToHalf(CellCenter(r, c), half) + Vector3.up * 0.05f;
                        Gizmos.DrawWireCube(p, new Vector3(tileSize * 0.96f, 0.1f, tileSize * 0.96f));
                    }

            Gizmos.color = new Color(1f, 0.85f, 0.2f);
            Gizmos.DrawWireCube(new Vector3(0f, -0.1f, 0f),
                                new Vector3(centerIslandHalfTiles.x * 2f * tileSize, 0.2f, centerIslandHalfTiles.y * 2f * tileSize));
            Gizmos.color = Color.white;
            Gizmos.DrawWireCube(new Vector3(0f, 0.5f, 0f), new Vector3(templeSize.x, 1f, templeSize.y));
            Gizmos.matrix = prev;
        }

        static Color GizmoColor(char ch, int half)
        {
            switch (ch)
            {
                case 'S': return half == 0 ? new Color(0.3f, 0.55f, 1f) : new Color(1f, 0.35f, 0.3f);
                case '=': return new Color(0.9f, 0.8f, 0.4f);
                case '^': case 'v': case '<': case '>': return new Color(0.4f, 0.9f, 0.4f);
                case 'D': return new Color(0.3f, 0.9f, 0.9f);
                case 'T': return new Color(0.9f, 0.4f, 0.9f);
                case 'J': case 'j': return Color.white;
                case 'C': case 'P': case 'W': case 'w': return new Color(0.7f, 0.5f, 0.3f);
                default: return new Color(0.6f, 0.6f, 0.6f);
            }
        }
