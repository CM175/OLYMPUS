// =====================================================================================
//  MapGenerator.cs
//  Procedural, symmetrical "Capture the Temple" Control map on Mount Olympus.
//  Everything (tiles, ramps, bridges, towers, temple, jump pads, hazards) is generated
//  from code using Unity primitives + tiny procedural meshes. No external modelling.
//
//  SETUP: Create an empty GameObject at (0,0,0), add MapGenerator, press
//  "Generate / Regenerate" in the inspector (or right-click the component > Generate Map).
//
//  IMPORTANT (Unity serialization rule): a MonoBehaviour must live in a file that has the
//  same name as the class, otherwise saved scenes show "Missing script". Before you SAVE a
//  scene containing a generated map, cut each block marked "MOVE TO OWN FILE" into its own
//  file named after the class (CapturePoint.cs, HermesJumpPad.cs, HermesLaunchDriver.cs,
//  KillZone.cs, OlympusSpawnPoint.cs). No code changes needed - they already use the
//  OlympusMap namespace. Alternatively tick "Generate On Start" and never save the map.
//
//  Blueprint symbols (one char = one tile, see MapGenerator.DefaultBlueprint):
//    .  void / cloud gap            #  floor tile              S  team spawn floor (+spawn points)
//    =  bridge (rails on open sides)  D  raised deck block      T  sniper tower (stairs toward spawn)
//    ^ v < >  ramp up toward +Z / -Z / +X / -X (to deck height)
//    C  waist-high cover   P  pillar   W  wall across X   w  wall along Z
//    J  Hermes pad -> temple roof     j  Hermes pad -> nearest tower top
// =====================================================================================
