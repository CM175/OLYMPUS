        public OlympusSpawnPoint GetRandomSpawnPoint(Team team)
        {
            OlympusSpawnPoint pick = null;
            int seen = 0;
            foreach (var sp in _spawnPoints)
            {
                if (sp == null || sp.team != team) continue;
                seen++;
                if (UnityEngine.Random.Range(0, seen) == 0) pick = sp; // reservoir sampling
            }
            return pick;
        }

        public OlympusSpawnPoint GetNearestSpawnPoint(Vector3 worldPosition)
        {
            OlympusSpawnPoint best = null;
            float bestSqr = float.MaxValue;
            foreach (var sp in _spawnPoints)
            {
                if (sp == null) continue;
                float d = (sp.transform.position - worldPosition).sqrMagnitude;
                if (d < bestSqr) { bestSqr = d; best = sp; }
            }
            return best;
        }

