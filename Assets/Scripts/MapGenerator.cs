        GameObject InstantiatePrefab(GameObject prefab, Transform parent)
        {
            if (prefab == null) return null;
            try
            {
#if UNITY_EDITOR
                if (!Application.isPlaying)
                    return PrefabUtility.InstantiatePrefab(prefab, parent) as GameObject;
#endif
                return Instantiate(prefab, parent, false);
            }
            catch (Exception e)
            {
                if (!_prefabWarned)
                {
                    _prefabWarned = true;
                    Debug.LogWarning($"[MapGenerator] Could not instantiate prefab override '{prefab.name}' " +
                                     $"(is it a scene object?). Falling back to primitives. {e.Message}", this);
                }
                return null;
            }
        }

        void StripColliders(GameObject go)
        {
            if (go == null) return;
            foreach (var col in go.GetComponentsInChildren<Collider>(true)) DestroyObject(col);
        }

        static void ApplyMaterial(GameObject go, Material mat)
        {
            if (mat == null) return;
            var r = go.GetComponent<Renderer>();
            if (r != null) r.sharedMaterial = mat;
        }

        static Quaternion LookRot(Vector3 dir)
        {
            dir.y = 0f;
            return dir.sqrMagnitude < 1e-6f ? Quaternion.identity : Quaternion.LookRotation(dir.normalized, Vector3.up);
        }

        void DestroyObject(UnityEngine.Object obj)
        {
            if (obj == null) return;
            if (Application.isPlaying) Destroy(obj);
            else DestroyImmediate(obj);
        }

