        void BuildJumpPad(char ch, string id, Vector3 center)
        {
            Vector3 start = center + Vector3.up * 0.05f;
            Vector3 target;
            if (ch == 'J') target = _roofTarget;
            else if (!TryNearestTowerTop(center, out target)) target = start + Vector3.up * towerHeight;
            CreateHermesPad("HermesPad_" + id, start, target);
        }

        bool TryNearestTowerTop(Vector3 from, out Vector3 top)
        {
            top = Vector3.zero;
            float best = float.MaxValue;
            bool found = false;
            foreach (var p in _towerTops)
            {
                Vector3 d = p - from;
                d.y = 0f;
                if (d.sqrMagnitude < best) { best = d.sqrMagnitude; top = p; found = true; }
            }
            return found;
        }

