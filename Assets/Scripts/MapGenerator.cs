        {
            foreach (var t in _root.GetComponentsInChildren<Transform>(true))
            if (t.gameObject.layer == LayerMask.NameToLayer("Default")) 
                t.gameObject.layer = generatedLayer;
        }

        // ==================================================================================
        //  BLUEPRINT / SYMMETRY HELPERS
        // ==================================================================================
        static List<string> ReadRows(string text)
        {
            var rows = new List<string>();
            foreach (string raw in text.Split('\n'))
            {
                string line = raw.TrimEnd('\r');
                string probe = line.Trim();
                if (probe.Length == 0 || probe.StartsWith("//")) continue;
                rows.Add(line);
            }
            return rows;
        }

        void ParseBlueprint()
        {
            List<string> rows = ReadRows(string.IsNullOrWhiteSpace(blueprint) ? DefaultBlueprint : blueprint);
            if (rows.Count == 0)
            {
                Debug.LogWarning("[MapGenerator] Blueprint has no rows - using the default blueprint.", this);
                rows = ReadRows(DefaultBlueprint);
            }

            _rows = rows.Count;
            _cols = 1;
            foreach (var row in rows) _cols = Mathf.Max(_cols, row.Length);

            _grid = new char[_rows, _cols];
            for (int r = 0; r < _rows; r++)
                for (int c = 0; c < _cols; c++)
                {
                    char ch = c < rows[r].Length ? rows[r][c] : '.';
                    _grid[r, c] = ch == ' ' ? '.' : ch;
                }
            _parsedBlueprint = blueprint;
            _warnedSymbols.Clear();
        }

        /// <summary>Cell centre in the Team A half. Row 0 = spawn (most negative Z), last row touches z = 0.</summary>
        Vector3 CellCenter(int r, int c)
        {
            return new Vector3((c - (_cols - 1) * 0.5f) * tileSize, 0f, -(_rows - r - 0.5f) * tileSize);
        }

        /// <summary>Maps a Team A position/direction into the requested half (0 = A, 1 = B).</summary>
        Vector3 ToHalf(Vector3 v, int half)
        {
            if (half == 0) return v;
            return symmetry == MapSymmetry.Rotate180 ? new Vector3(-v.x, v.y, -v.z) : new Vector3(v.x, v.y, -v.z);
        }

        bool IsReserved(int r, int c)
        {
            Vector3 p = CellCenter(r, c);
            float limX = centerIslandHalfTiles.x * tileSize + tileSize * 0.5f - 0.01f;
            float limZ = centerIslandHalfTiles.y * tileSize + tileSize * 0.5f - 0.01f;
            return Mathf.Abs(p.x) < limX && Mathf.Abs(p.z) < limZ;
        }

        /// <summary>Safe cell lookup in Team A coordinates. r == rows reads across the centre seam.</summary>
        char GetCell(int r, int c)
        {
            if (r < 0 || c < 0 || c >= _cols || r > _rows) return '.';
            if (r == _rows)
            {
                c = symmetry == MapSymmetry.Rotate180 ? _cols - 1 - c : c;
                r = _rows - 1;
            }
            if (IsReserved(r, c)) return '#'; // the temple island is solid ground
            return _grid[r, c];
        }

        // ==================================================================================
        //  CELLS
        // ==================================================================================
        void BuildCell(int r, int c, int half)
        {
            char ch = _grid[r, c];
            if (ch == '.' || IsReserved(r, c)) return;

            string tag = half == 0 ? "A" : "B";
            string id = $"{tag}_{r}_{c}";
            Vector3 center = ToHalf(CellCenter(r, c), half);

            // ---- ground
            if (ch == '=')
            {
                PlaceBox("Bridge_" + id, _env, center + Vector3.down * (bridgeThickness * 0.5f),
                         new Vector3(tileSize, bridgeThickness, tileSize), Quaternion.identity, FloorMat, floorTilePrefab);
            }
            else
            {
                Material mat = ch == 'S' ? (half == 0 ? TeamAMat : TeamBMat) : FloorMat;
                PlaceBox("Tile_" + id, _env, center + Vector3.down * (tileThickness * 0.5f),
                         new Vector3(tileSize, tileThickness, tileSize), Quaternion.identity, mat, floorTilePrefab);
                BuildRockUnderside("Tile_" + id, center, new Vector2(tileSize, tileSize), r * 131 + c * 17 + 7, 1f);
            }

            // ---- features
            switch (ch)
            {
                case '#': break;
                case 'S': BuildSpawn(r, c, half, center, id); break;
                case '=': BuildEdgeWalls(r, c, half, center, railHeight, 0.3f, MarbleMat, "Rail_" + id, _env); break;
                case '^': BuildRamp(ch, half, center, id); break;
                case 'v': BuildRamp(ch, half, center, id); break;
                case '<': BuildRamp(ch, half, center, id); break;
                case '>': BuildRamp(ch, half, center, id); break;
                case 'D':
                    PlaceBox("Deck_" + id, _env, center + Vector3.up * (deckHeight * 0.5f),
                             new Vector3(tileSize, deckHeight, tileSize), Quaternion.identity, MarbleMat);
                    break;
                case 'T': BuildTower(id, half, center); break;
                case 'C':
                    PlaceBox("Cover_" + id, _cover, center + Vector3.up * (coverHeight * 0.5f),
                             new Vector3(tileSize * 0.7f, coverHeight, 0.9f), Quaternion.identity, CoverMat, coverPrefab);
                    break;
                case 'P':
                    PlaceCylinder("Pillar_" + id, _cover, center, 0.7f, pillarHeight, MarbleMat, columnPrefab);
                    break;
                case 'W':
                    PlaceBox("Wall_" + id, _cover, center + Vector3.up * (wallHeight * 0.5f),
                             new Vector3(tileSize * 0.9f, wallHeight, 0.8f), Quaternion.identity, CoverMat, wallPrefab);
                    break;
                case 'w':
                    PlaceBox("Wall_" + id, _cover, center + Vector3.up * (wallHeight * 0.5f),
                             new Vector3(0.8f, wallHeight, tileSize * 0.9f), Quaternion.identity, CoverMat, wallPrefab);
                    break;
                case 'J':
                case 'j':
                    BuildJumpPad(ch, id, center);
                    break;
                default:
                    if (_warnedSymbols.Add(ch))
                        Debug.LogWarning($"[MapGenerator] Unknown blueprint symbol '{ch}' - built as a plain floor tile.", this);
                    break;
            }
        }

        void BuildSpawn(int r, int c, int half, Vector3 center, string id)
        {
            // Walls on every open (void) edge so nobody walks off the spawn room.
            BuildEdgeWalls(r, c, half, center, spawnWallHeight, 0.6f, CoverMat, "SpawnWall_" + id, _env);

            Team assignedTeam = half == 0 ? Team.TeamA : Team.TeamB;
            int n = Mathf.Max(1, spawnGridPerTile);

            // Keep points away from edge walls (0.6f thick) and adjacent tiles
            float usableSpan = Mathf.Max(0.5f, tileSize - 1.6f);
            Quaternion rot = LookRot(ToHalf(Vector3.forward, half)); // face toward the centre island

            for (int i = 0; i < n; i++)
            {
                for (int j = 0; j < n; j++)
                {
                    float tX = n == 1 ? 0f : (i / (float)(n - 1)) - 0.5f;
                    float tZ = n == 1 ? 0f : (j / (float)(n - 1)) - 0.5f;

                    Vector3 localOffset = new Vector3(tX * usableSpan, 0.02f, tZ * usableSpan);
                    var go = new GameObject($"SpawnPoint_{id}_{i}{j}");
                    go.transform.SetParent(_spawns, false);
                    go.transform.localPosition = center + localOffset;
                    go.transform.localRotation = rot;

                    var sp = go.AddComponent<OlympusSpawnPoint>();
                    sp.team = assignedTeam;
                }
            }
        }
        void BuildEdgeWalls(int r, int c, int half, Vector3 center, float height, float thickness,
                            Material mat, string prefix, Transform parent)
        {
            for (int i = 0; i < 4; i++)
            {
                int dr = NeighborDR[i], dc = NeighborDC[i];
                if (GetCell(r + dr, c + dc) != '.') continue;

                Vector3 dir = ToHalf(new Vector3(dc, 0f, dr), half);
                bool spansX = dr != 0;
                Vector3 size = spansX ? new Vector3(tileSize, height, thickness) : new Vector3(thickness, height, tileSize);
                Vector3 pos = center + dir * (tileSize * 0.5f - thickness * 0.5f) + Vector3.up * (height * 0.5f);
                PlaceBox($"{prefix}_{i}", parent, pos, size, Quaternion.identity, mat, wallPrefab);
            }
        }

        void BuildRamp(char ch, int half, Vector3 center, string id)
        {
            Vector3 baseDir = ch == '^' ? Vector3.forward : ch == 'v' ? Vector3.back : ch == '>' ? Vector3.right : Vector3.left;
            Vector3 dir = ToHalf(baseDir, half); // mirrored along with the map
            PlaceWedge("Ramp_" + id, _env, center + Vector3.up * (deckHeight * 0.5f), LookRot(dir),
                       new Vector3(tileSize, deckHeight, tileSize), MarbleMat);
        }

        // ---------------------------------------------------------------- Sniper tower
        void BuildTower(string id, int half, Vector3 center)
        {
            Vector3 spawnDir = ToHalf(Vector3.back, half); // stairs run toward the team's own spawn
            float t = tileSize;
            float topY = towerHeight;
            Material marble = MarbleMat;

            bool usedPrefab = false;
            if (towerPrefab != null)
            {
                GameObject body = InstantiatePrefab(towerPrefab, _towers);
                if (body != null)
                {
                    body.name = "TowerBody_" + id;
                    body.transform.localPosition = center + Vector3.up * (topY * 0.5f);
                    body.transform.localRotation = Quaternion.identity;
                    body.transform.localScale = new Vector3(t, topY, t);
                    usedPrefab = true;
                }
            }

            float platformSize = t + 0.6f;
            float platformHalf = platformSize * 0.5f;

            if (!usedPrefab)
            {
                const float leg = 0.9f;
                for (int sx = -1; sx <= 1; sx += 2)
                    for (int sz = -1; sz <= 1; sz += 2)
                        PlaceBox($"TowerLeg_{id}_{sx}{sz}", _towers,
                                 center + new Vector3(sx * (t * 0.5f - leg * 0.5f), topY * 0.5f, sz * (t * 0.5f - leg * 0.5f)),
                                 new Vector3(leg, topY, leg), Quaternion.identity, marble);

                PlaceBox("TowerPlatform_" + id, _towers, center + Vector3.up * (topY - towerPlatformThickness * 0.5f),
                         new Vector3(platformSize, towerPlatformThickness, platformSize), Quaternion.identity, marble);

                Vector3[] axes = { Vector3.forward, Vector3.back, Vector3.left, Vector3.right };
                for (int i = 0; i < axes.Length; i++)
                {
                    if (towerStairs && Vector3.Dot(axes[i], spawnDir) > 0.9f) continue; // stair entrance stays open
                    bool spansX = Mathf.Abs(axes[i].z) > 0.5f;
                    Vector3 size = spansX ? new Vector3(platformSize, towerParapetHeight, 0.35f)
                                          : new Vector3(0.35f, towerParapetHeight, platformSize);
                    Vector3 pos = center + axes[i] * (platformHalf - 0.175f) + Vector3.up * (topY + towerParapetHeight * 0.5f);
                    PlaceBox($"TowerParapet_{id}_{i}", _towers, pos, size, Quaternion.identity, CoverMat, coverPrefab);
                }
            }

            if (towerStairs)
            {
                int n = Mathf.CeilToInt(topY / towerStairRise);
                Quaternion rot = LookRot(spawnDir);
                for (int k = 0; k < n - 1; k++)
                {
                    float stepTop = topY - (k + 1) * towerStairRise;
                    if (stepTop <= 0.05f) break;
                    float dist = platformHalf + (k + 0.5f) * towerStairTread;
                    PlaceBox($"TowerStair_{id}_{k}", _towers, center + spawnDir * dist + Vector3.up * (stepTop * 0.5f),
                             new Vector3(towerStairWidth, stepTop, towerStairTread), rot, marble);
                }
            }

            _towerTops.Add(center + Vector3.up * topY);
        }

