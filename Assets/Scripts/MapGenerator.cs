        [ContextMenu("Generate Map")]
        public void Generate()
        {
            ClearGenerated();
            ParseBlueprint();
            CreateGroups();
            _towerTops.Clear();

            BuildCenterIsland();
            BuildTemple();

            // Pass 0: everything except pads. Pass 1: pads (they aim at towers/roof built in pass 0).
            for (int pass = 0; pass < 2; pass++)
                for (int half = 0; half < 2; half++)
                    for (int r = 0; r < _rows; r++)
                        for (int c = 0; c < _cols; c++)
                        {
                            char ch = _grid[r, c];
                            bool isPad = ch == 'J' || ch == 'j';
                            if ((pass == 1) != isPad) continue;
                            BuildCell(r, c, half);
                        }

            if (buildCloudVisual) BuildCloudSea();
            BuildDeathZone();
            ApplyLayer();
            CacheReferences();

            if (logSummary)
                Debug.Log($"[MapGenerator] Generated {_root.GetComponentsInChildren<Transform>(true).Length - 1} objects, " +
                          $"{_spawnPoints.Count} spawn points, {_jumpPads.Count} Hermes pads, {_towerTops.Count} towers.", this);

            MapGenerated?.Invoke(this);
#if UNITY_EDITOR
            if (!Application.isPlaying)
            {
                EditorUtility.SetDirty(this);
                if (gameObject.scene.IsValid()) EditorSceneManager.MarkSceneDirty(gameObject.scene);
            }
#endif
        }

        [ContextMenu("Clear Generated Map")]
        public void ClearGenerated()
        {
            // Only ever touches the child named "Generated" - your own children are never deleted.
            for (int i = transform.childCount - 1; i >= 0; i--)
            {
                Transform child = transform.GetChild(i);
                if (child.name != GeneratedRootName) continue;
                child.name = GeneratedRootName + "_Deleting"; // so Find() can't match it while Destroy() is deferred
                child.gameObject.SetActive(false);
                DestroyObject(child.gameObject);
            }
            foreach (var m in _fallbackMaterials.Values) DestroyObject(m);
            _fallbackMaterials.Clear();
            foreach (var o in _ownedAssets) DestroyObject(o);
            _ownedAssets.Clear();
            _wedgeMesh = null;

            _root = _env = _cover = _towers = _temple = _pads = _spawns = _triggers = null;
            _towerTops.Clear();
            _spawnPoints.Clear();
            _jumpPads.Clear();
            CapturePoint = null;
            DeathZone = null;
        }

