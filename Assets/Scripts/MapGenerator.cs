        /// <summary>
        /// Pitched, walkable roof: two sloped slabs + a flat ridge deck (landing strip for 'J' pads)
        /// and two triangular-ish pediments closing the gable ends. Pitch stays below typical slope limits.
        /// </summary>
        void BuildRoof(float eavesY, float hxColumns, float hzColumns)
        {
            Material marble = MarbleMat;
            float pitch = roofPitchDegrees * Mathf.Deg2Rad;
            float cos = Mathf.Cos(pitch), sin = Mathf.Sin(pitch);
            float hxRoof = templeSize.x * 0.5f + roofOverhang;
            float ridgeHalf = roofRidgeWidth * 0.5f;
            float run = Mathf.Max(0.5f, hxRoof - ridgeHalf);
            float rise = run * Mathf.Tan(pitch);
            float slopeLen = run / cos;
            float roofLen = templeSize.y + roofOverhang * 2f;
            float ridgeY = eavesY + rise;

            for (int side = -1; side <= 1; side += 2)
            {
                Vector3 mid = new Vector3(side * (ridgeHalf + run * 0.5f), eavesY + rise * 0.5f, 0f);
                Vector3 normal = new Vector3(side * sin, cos, 0f);
                Vector3 center = mid - normal * (roofThickness * 0.5f); // top surface passes through eaves + ridge edge
                PlaceBox("RoofSlope_" + (side < 0 ? "L" : "R"), _temple, center,
                         new Vector3(slopeLen, roofThickness, roofLen), Quaternion.Euler(0f, 0f, -side * roofPitchDegrees), marble);
            }
            PlaceBox("RoofRidge", _temple, new Vector3(0f, ridgeY - roofThickness * 0.5f, 0f),
                     new Vector3(roofRidgeWidth + 0.1f, roofThickness, roofLen), Quaternion.identity, marble);

            // Pediments (front/back gables)
            float hxPed = hxColumns + entablatureDepth * 0.5f;
            float yEdge = Mathf.Max(0.15f, (hxRoof - hxPed) * Mathf.Tan(pitch) - roofThickness / cos);
            float yRidge = Mathf.Max(yEdge + 0.2f, rise - roofThickness);
            var poly = new List<Vector2>
            {
                new Vector2(-hxPed, 0f), new Vector2(hxPed, 0f),
                new Vector2(hxPed, yEdge), new Vector2(ridgeHalf, yRidge),
                new Vector2(-ridgeHalf, yRidge), new Vector2(-hxPed, yEdge)
            };
            Mesh pedMesh = BuildPrismMesh(poly, entablatureDepth * 0.8f, Quaternion.identity, "OlympusPediment");
            _ownedAssets.Add(pedMesh);
            for (int s = -1; s <= 1; s += 2)
                PlaceMeshObject("Pediment_" + (s < 0 ? "Back" : "Front"), _temple, pedMesh,
                                new Vector3(0f, eavesY, s * hzColumns), Quaternion.identity, Vector3.one, marble);

            _roofTarget = new Vector3(0f, ridgeY + 0.1f, 0f); // where 'J' pads aim
        }

