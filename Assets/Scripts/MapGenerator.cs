        void BuildTempleColumnsAndRoof()
        {
            float y0 = _templePlatformY;
            float hx = templeSize.x * 0.5f - columnInset;
            float hz = templeSize.y * 0.5f - columnInset;
            int nf = Mathf.Max(2, columnsFront);
            int ns = Mathf.Max(2, columnsSide);

            float gapFront = 2f * hx / (nf - 1) - 2f * columnRadius;
            float gapSide = 2f * hz / (ns - 1) - 2f * columnRadius;
            if (gapFront < 1.6f || gapSide < 1.6f)
                Debug.LogWarning($"[MapGenerator] Temple column gaps are narrow (front {gapFront:0.0} m, side {gapSide:0.0} m). " +
                                 "Heroes may get stuck - reduce column counts or widen the temple.", this);

            // ---- perimeter columns
            int index = 0;
            for (int i = 0; i < nf; i++)
            {
                float x = Mathf.Lerp(-hx, hx, i / (float)(nf - 1));
                BuildColumn(index++, new Vector3(x, y0, hz));
                BuildColumn(index++, new Vector3(x, y0, -hz));
            }
            for (int j = 1; j < ns - 1; j++)
            {
                float z = Mathf.Lerp(-hz, hz, j / (float)(ns - 1));
                BuildColumn(index++, new Vector3(hx, y0, z));
                BuildColumn(index++, new Vector3(-hx, y0, z));
            }

            // ---- entablature (architrave beams) resting on the columns
            float beamY = y0 + columnHeight + entablatureHeight * 0.5f;
            Material marble = MarbleMat;
            for (int s = -1; s <= 1; s += 2)
            {
                PlaceBox("Architrave_Z" + s, _temple, new Vector3(0f, beamY, s * hz),
                         new Vector3(2f * hx + entablatureDepth, entablatureHeight, entablatureDepth), Quaternion.identity, marble);
                PlaceBox("Architrave_X" + s, _temple, new Vector3(s * hx, beamY, 0f),
                         new Vector3(entablatureDepth, entablatureHeight, 2f * hz + entablatureDepth), Quaternion.identity, marble);
            }

            BuildRoof(y0 + columnHeight + entablatureHeight, hx, hz);
        }

