        public void CacheReferences()
        {
            Transform root = _root != null ? _root : transform.Find(GeneratedRootName);
            _spawnPoints.Clear();
            _jumpPads.Clear();
            CapturePoint = null;
            DeathZone = null;
            if (root == null) return;
            CapturePoint = root.GetComponentInChildren<CapturePoint>(true);
            DeathZone = root.GetComponentInChildren<KillZone>(true);
            _spawnPoints.AddRange(root.GetComponentsInChildren<OlympusSpawnPoint>(true));
            _jumpPads.AddRange(root.GetComponentsInChildren<HermesJumpPad>(true));
        }

