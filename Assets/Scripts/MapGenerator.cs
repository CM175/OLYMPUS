        Material Mat(Material assigned, string key, Color color, bool emissive = false)
        {
            if (assigned != null) return assigned;
            if (_fallbackMaterials.TryGetValue(key, out Material cached) && cached != null) return cached;
            Material created = CreateFallbackMaterial(key, color, emissive);
            if (created != null) _fallbackMaterials[key] = created;
            return created; // may be null -> primitives keep their own default material
        }

        static Material CreateFallbackMaterial(string key, Color color, bool emissive)
        {
            Shader shader = null;
            RenderPipelineAsset rp = GraphicsSettings.currentRenderPipeline;
            if (rp != null && rp.defaultMaterial != null) shader = rp.defaultMaterial.shader; // URP / HDRP safe
            if (shader == null) shader = Shader.Find("Standard");
            if (shader == null) shader = Shader.Find("Universal Render Pipeline/Lit");
            if (shader == null) shader = Shader.Find("Sprites/Default");
            if (shader == null) return null;

            var mat = new Material(shader) { name = "OlympusFallback_" + key };
            if (mat.HasProperty("_BaseColor")) mat.SetColor("_BaseColor", color);
            if (mat.HasProperty("_Color")) mat.SetColor("_Color", color);
            if (emissive && mat.HasProperty("_EmissionColor"))
            {
                mat.EnableKeyword("_EMISSION");
                mat.SetColor("_EmissionColor", color * 1.5f);
            }
            return mat;
        }

